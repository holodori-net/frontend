import { Theme } from '@primeuix/themes'
import * as PrimeVueCore from '@primevue/core'
import * as metadata from '@primevue/metadata'
import {
  primeVueComponents,
  primeVueStyleDependencies,
} from '../../shared/primevue.ts'

type StyleDefinition = {
  name: string
  from: string
}

type StyleApi = {
  style?: unknown
  getStyleSheet?: (css?: string, props?: Record<string, string>) => string
  getCommonThemeStyleSheet?: (
    params?: undefined,
    props?: Record<string, string>,
  ) => string
  getThemeStyleSheet?: (
    params?: undefined,
    props?: Record<string, string>,
  ) => string
}

type StyleSheet = {
  id: string
  css: string
}

// PrimeVue's declarations omit these runtime style exports.
const core = PrimeVueCore as unknown as {
  BaseStyle: StyleApi
  BaseComponentStyle: StyleApi
}

const allowlist = new Set<string>(primeVueComponents)
const registeredComponents = metadata.components.filter(
  (component): component is StyleDefinition =>
    typeof component.name === 'string' &&
    typeof component.from === 'string' &&
    allowlist.has(component.name),
)

if (registeredComponents.length !== primeVueComponents.length) {
  const found = new Set(registeredComponents.map(({ name }) => name))
  const missing = primeVueComponents.filter((name) => !found.has(name))
  throw new Error(
    `PrimeVue metadata is missing allowlisted components: ${missing.join(', ')}`,
  )
}

async function importStyleApi(from: string): Promise<StyleApi> {
  const module = (await import(`${from}/style`)) as {
    default?: StyleApi
  }
  if (!module.default) {
    throw new Error(
      `PrimeVue style module has no default export: ${from}/style`,
    )
  }
  return module.default
}

function getDependencyStyleApis() {
  const components = new Set<string>()
  const directives = new Set<string>()

  for (const component of registeredComponents) {
    const dependencies =
      primeVueStyleDependencies[
        component.name as keyof typeof primeVueStyleDependencies
      ]
    for (const name of dependencies?.components ?? []) {
      if (!allowlist.has(name)) components.add(name)
    }
    for (const name of dependencies?.directives ?? []) directives.add(name)
  }

  const componentStyles = [...components].map(async (name) => {
    const definition = metadata.components.find(
      (item) => item.name?.toLowerCase() === name.toLowerCase(),
    )
    if (!definition?.from) {
      throw new Error(
        `PrimeVue metadata is missing dependency component: ${name}`,
      )
    }
    return { name, api: await importStyleApi(definition.from) }
  })
  const directiveStyles = [...directives].map(async (name) => {
    const definition = metadata.directives.find(
      (item) => item.name?.toLowerCase() === name.toLowerCase(),
    )
    if (!definition?.from) {
      throw new Error(
        `PrimeVue metadata is missing dependency directive: ${name}`,
      )
    }
    return {
      name: `${name}Directive`,
      api: await importStyleApi(definition.from),
    }
  })

  return Promise.all([...componentStyles, ...directiveStyles])
}

/** Parse the exact style wrappers generated by PrimeVue's style APIs. */
export function extractPrimeVueStyleSheets(
  output: string,
  source: string,
  options: { allowEmpty?: boolean } = {},
): StyleSheet[] {
  if (typeof output !== 'string') {
    throw new Error(`PrimeVue returned invalid styles for ${source}`)
  }
  if (output.length === 0 && options.allowEmpty) return []
  if (output.length === 0) {
    throw new Error(`PrimeVue generated no styles for ${source}`)
  }

  const sheets: StyleSheet[] = []
  const styleTag =
    /<style type="text\/css" data-primevue-style-id="([^"]+)"(?:\s[^>]*)?>([\s\S]*?)<\/style>/gy
  let offset = 0

  while (offset < output.length) {
    styleTag.lastIndex = offset
    const match = styleTag.exec(output)
    if (!match || match.index !== offset) {
      throw new Error(`Unexpected PrimeVue style output for ${source}`)
    }

    const [, id, css] = match
    if (!id || !css?.trim()) {
      throw new Error(`PrimeVue generated an empty style for ${source}`)
    }

    sheets.push({ id, css })
    offset = styleTag.lastIndex
  }

  if (sheets.length === 0) {
    throw new Error(`PrimeVue generated no style blocks for ${source}`)
  }

  return sheets
}

function callStyleApi(
  api: StyleApi,
  method: keyof StyleApi,
  source: string,
): string {
  const call = api[method]
  if (typeof call !== 'function') {
    throw new Error(`PrimeVue style API ${method} is unavailable for ${source}`)
  }
  return call.call(api)
}

/** Generate theme and component CSS using the PrimeVue module's style APIs. */
export async function generatePrimeVueStyles(
  theme: unknown,
): Promise<{ css: string; styleIds: string[] }> {
  Theme.setTheme(theme as Parameters<typeof Theme.setTheme>[0])

  const componentStyles = await Promise.all(
    registeredComponents.map(async (component) => ({
      name: component.name,
      api: await importStyleApi(component.from),
    })),
  )
  const styleApis = [
    { name: 'BaseStyle', api: core.BaseStyle },
    { name: 'BaseComponentStyle', api: core.BaseComponentStyle },
    ...componentStyles.map(({ name, api }) => ({
      name: `${name}Style`,
      api,
    })),
  ]
  const dependencyStyleApis = await getDependencyStyleApis()

  const sheets: StyleSheet[] = []
  for (const { name, api } of styleApis) {
    sheets.push(
      ...extractPrimeVueStyleSheets(
        callStyleApi(api, 'getStyleSheet', name),
        `${name}.getStyleSheet`,
        { allowEmpty: true },
      ),
    )
  }

  sheets.push(
    ...extractPrimeVueStyleSheets(
      callStyleApi(core.BaseStyle, 'getCommonThemeStyleSheet', 'BaseStyle'),
      'BaseStyle.getCommonThemeStyleSheet',
    ),
  )

  for (const { name, api } of styleApis) {
    sheets.push(
      ...extractPrimeVueStyleSheets(
        callStyleApi(api, 'getThemeStyleSheet', name),
        `${name}.getThemeStyleSheet`,
        // Some child components share their theme CSS with a parent style API.
        { allowEmpty: !api.style },
      ),
    )
  }

  for (const { name, api } of dependencyStyleApis) {
    sheets.push(
      ...extractPrimeVueStyleSheets(
        callStyleApi(api, 'getStyleSheet', name),
        `${name}.getStyleSheet`,
        { allowEmpty: true },
      ),
      ...extractPrimeVueStyleSheets(
        callStyleApi(api, 'getThemeStyleSheet', name),
        `${name}.getThemeStyleSheet`,
      ),
    )
  }

  const ids = new Set<string>()
  for (const { id } of sheets) {
    if (ids.has(id)) {
      throw new Error(`PrimeVue generated duplicate style ID: ${id}`)
    }
    ids.add(id)
  }

  return {
    css: sheets.map(({ css }) => css).join('\n'),
    styleIds: sheets.map(({ id }) => id),
  }
}
